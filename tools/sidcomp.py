#!/usr/bin/env python3
"""Compress the SID combined-waveform tables in sid_tables.sv into
   index ROM (which 16-byte block)  +  block ROM (deduplicated blocks).

   sidcomp.py <in sid_tables.sv> <out sid_tables.sv> <outdir for test vectors>

   Lookup (two pipeline stages, same total latency as before thanks to acc_next):
     stage 1 (clock with acc_next/mode_next):  blk_pt = IDX[{0, mode, acc[10:4]}]
                                               blk_ps = IDX[256 + (mode ? acc[11:4] : acc[10:4])]
     stage 2 (next clock, acc_t = same value): p_t = BLK[{blk_pt, acc_t[3:0]}], ps = BLK[{blk_ps, acc_t[3:0]}]
"""
import re, sys

src_path, out_path, vec_dir = sys.argv[1:4]
src = open(src_path).read()

def table(name):
    m = re.search(r'wire \[7:0\] ' + name + r'\s*\[0:(\d+)\]\s*=\s*\'\{(.*?)\};', src, re.S)
    vals = [int(v, 16) for v in re.findall(r"'h([0-9A-Fa-f]{2})", m.group(2))]
    assert len(vals) == int(m.group(1)) + 1, name
    return vals, m

t6pt, m6pt = table('wave6581_p_t')
t6ps, m6ps = table('wave6581_ps_')
t8pt, m8pt = table('wave8580_p_t')
t8ps, m8ps = table('wave8580_ps_')

blocks = {(0,) * 16: 0}
order = [(0,) * 16]
def blk(vals, i):
    b = tuple(vals[i * 16:(i + 1) * 16])
    if b not in blocks:
        blocks[b] = len(order)
        order.append(b)
    return blocks[b]

idx = [0] * 1024
for a in range(128):            # p_t: 6581 at 0..127, 8580 at 128..255
    idx[a] = blk(t6pt, a)
    idx[128 + a] = blk(t8pt, a)
for a in range(128):            # ps 6581: 256..383
    idx[256 + a] = blk(t6ps, a)
for a in range(256):            # ps 8580: 512..767
    idx[512 + a] = blk(t8ps, a)
nblk = len(order)
assert nblk <= 256, nblk
data = [v for b in order for v in b] + [0] * ((256 - nblk) * 16)
print(f"unique blocks incl. zero: {nblk}, block ROM {nblk*16} bytes used of 4096")

# --- self check: reproduce every original entry through the two-stage lookup
def look(mode, acc):
    bpt = idx[(mode << 7) | ((acc >> 4) & 0x7f)]
    bps = idx[256 + (((1 << 8) | ((acc >> 4) & 0xff)) if mode else ((acc >> 4) & 0x7f))]
    return data[(bpt << 4) | (acc & 15)], data[(bps << 4) | (acc & 15)]
for acc in range(4096):
    pt, ps = look(0, acc)
    assert pt == t6pt[acc & 0x7ff] and ps == t6ps[acc & 0x7ff], ('6581', acc)
    pt, ps = look(1, acc)
    assert pt == t8pt[acc & 0x7ff] and ps == t8ps[acc], ('8580', acc)
print("python equivalence: all 2 x 4096 inputs OK")

# --- test vectors for the HDL check (expected p_t, ps for mode 0/1, all acc)
with open(f"{vec_dir}/expect.hex", "w") as f:
    for mode in (0, 1):
        for acc in range(4096):
            pt = (t8pt if mode else t6pt)[acc & 0x7ff]
            ps = t8ps[acc] if mode else t6ps[acc & 0x7ff]
            f.write(f"{pt:02x}{ps:02x}\n")

def sv_array(name, width, vals):
    lines = []
    for i in range(0, len(vals), 16):
        lines.append("\t" + ", ".join(f"'h{v:0{width // 4}x}" for v in vals[i:i + 16]))
    return f"reg [{width-1}:0] {name}[0:{len(vals)-1}] = '{{\n" + ",\n".join(lines) + "\n};\n"

# --- rewrite sid_tables.sv
new = src
# drop the four original tables
for m in (m6pt, m6ps, m8pt, m8ps):
    new = new.replace(m.group(0), "")
old_pt = re.search(r"// P \+ T\nalways @\(posedge clock\) begin\n\tp_t_out <= .*?\nend\n", new, re.S).group(0)
old_ps = re.search(r"// P \+ S\nalways @\(posedge clock\) begin\n\tps__out <= .*?\nend\n", new, re.S).group(0)
lookup = (
"// P + T and P + S: compressed tables (generated by sidcomp.py from the original MiSTer tables).\n"
"// Stage 1 runs one clock early from acc_next/mode_next, stage 2 uses acc_t, so the\n"
"// outputs are valid on the same clock as with the original single-stage tables.\n"
+ sv_array("wave_idx", 8, idx) + sv_array("wave_blk", 8, data) +
"reg [7:0] blk_pt, blk_ps;\n"
"always @(posedge clock) begin\n"
"\tblk_pt <= wave_idx[{2'b00, mode_next, acc_next[10:4]}];\n"
"\tblk_ps <= wave_idx[mode_next ? {2'b10, acc_next[11:4]} : {3'b010, acc_next[10:4]}];\n"
"end\n"
"always @(posedge clock) begin\n"
"\tp_t_out <= wave_blk[{blk_pt, acc_t[3:0]}];\n"
"\tps__out <= wave_blk[{blk_ps, acc_t[3:0]}];\n"
"end\n")
new = new.replace(old_pt, lookup).replace(old_ps, "")
new = new.replace("\tinput      [11:0] acc_t,\n",
                  "\tinput      [11:0] acc_t,\n\tinput      [11:0] acc_next,   // voice accumulator one clock ahead (index stage)\n"
                  "\tinput             mode_next,  // SID type for that voice\n", 1)
assert "acc_next" in new and "wave6581_p_t[" not in new and "wave8580_ps_[" not in new
open(out_path, "w").write(new)
print("wrote", out_path)
